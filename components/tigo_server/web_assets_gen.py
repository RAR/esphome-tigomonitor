"""Generate web_assets.h from components/tigo_server/web/*.html.

The ESP32 keeps each page gzipped in flash. A page with the API-token
placeholder is split there and stored as two pieces of one gzip stream:

  <PAGE>_HTML_GZ_PRE   gzip header + the text before the placeholder,
                       deflated and sync-flushed (byte-aligned, not final)
  <PAGE>_HTML_GZ_POST  the text after it, deflated as the final blocks

At request time gzip_splice.h sends PRE, a stored block holding the token,
POST, and a trailer whose CRC it combines from the CRCs recorded here. The
page is never inflated on the device.

Pages without the placeholder are stored the same way with an empty token.

Standalone (no ESPHome import), so the host test can run it:
  python3 components/tigo_server/web_assets_gen.py --out build/web_assets.h
"""
import argparse
import zlib
from pathlib import Path

WEB_PAGES = ['app']
TOKEN_PLACEHOLDER = b'__TIGO_API_TOKEN__'
GZIP_HEADER = bytes([0x1F, 0x8B, 0x08, 0x00, 0, 0, 0, 0, 0x02, 0xFF])


def _deflate(data: bytes, final: bool) -> bytes:
    c = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
    return c.compress(data) + c.flush(zlib.Z_FINISH if final else zlib.Z_SYNC_FLUSH)


def _array(name: str, data: bytes) -> list:
    lines = [f'inline constexpr uint8_t {name}[{len(data)}] = {{']
    for i in range(0, len(data), 24):
        lines.append('  ' + ','.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',')
    lines.append('};')
    return lines


def generate(web_dir: Path) -> str:
    lines = [
        '// Auto-generated by tigo_server/web_assets_gen.py — do not edit.',
        '// Source: components/tigo_server/web/*.html',
        '#pragma once',
        '#include <cstdint>',
        '#include "gzip_splice.h"',
        'namespace esphome {',
        'namespace tigo_server {',
        '',
    ]
    for page in WEB_PAGES:
        path = web_dir / f'{page}.html'
        if not path.exists():
            raise FileNotFoundError(f'expected web asset {path}')
        content = path.read_bytes()
        pre, sep, post = content.partition(TOKEN_PLACEHOLDER)
        if not sep:
            pre, post = content, b''
        base = f'{page.upper()}_HTML'
        lines += _array(f'{base}_GZ_PRE', GZIP_HEADER + _deflate(pre, final=False))
        lines += _array(f'{base}_GZ_POST', _deflate(post, final=True))
        lines += [
            f'inline constexpr tigo_gzip::SplicedPage {base}_GZ = {{',
            f'  {base}_GZ_PRE, sizeof({base}_GZ_PRE), 0x{zlib.crc32(pre):08x}u, {len(pre)}u,',
            f'  {base}_GZ_POST, sizeof({base}_GZ_POST), 0x{zlib.crc32(post):08x}u, {len(post)}u,',
            '};',
            '',
        ]
    lines += ['}  // namespace tigo_server', '}  // namespace esphome', '']
    return '\n'.join(lines)


def write(out: Path, web_dir: Path) -> None:
    text = generate(web_dir)
    # Leave the file alone when nothing changed, so the build doesn't
    # recompile the web server on every config.
    if not out.exists() or out.read_text() != text:
        out.write_text(text)


if __name__ == '__main__':
    here = Path(__file__).parent
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', type=Path, default=here / 'web_assets.h')
    ap.add_argument('--web-dir', type=Path, default=here / 'web')
    a = ap.parse_args()
    write(a.out, a.web_dir)
